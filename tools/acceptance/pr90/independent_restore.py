"""Independent full snapshot restore of the disposable PR90 Moodle site.

Invoked ONLY by the existing isolated GitHub Actions rehearsal, using its
already captured full code, config, moodledata and SQL snapshot. Restores
into separate filesystem directories and a DIFFERENT synthetic MySQL DB.
Does not boot or modify production, shared dev or an external Moodle clone.
"""
from __future__ import annotations

import hashlib
from pathlib import Path
import shutil
import subprocess


class IndependentRestoreHold(RuntimeError):
    pass


DB = "bmsci_independent_restore"


def require(ok: bool, reason: str):
    if not ok:
        raise IndependentRestoreHold(reason)


def verify_independent_restore(*, snapshot: Path, root: Path, dbargs: list,
                               cmd, digest_tree, original_code: dict,
                               original_data: dict, original_sql_sha256: str) -> dict:
    """Restore full synthetic snapshot without touching source or original DB.

    cmd is the existing PR90 rehearsal's subprocess wrapper, which is already
    constrained to GitHub Actions localhost Moodle+DB.
    """
    snapshot = Path(snapshot).resolve()
    root = Path(root).resolve()
    require(snapshot == root / "snapshot", "only the active PR90 snapshot allowed")
    for required in ("code", "data", "db.sql"):
        require((snapshot / required).exists(), "missing snapshot component: " + required)
    source_sql = snapshot / "db.sql"
    require(source_sql.is_file() and source_sql.stat().st_size > 100,
            "missing independent SQL data")
    require(hashlib.sha256(source_sql.read_bytes()).hexdigest() == original_sql_sha256,
            "snapshot SQL mutated after capture")
    require(digest_tree(snapshot / "code") == original_code,
            "original code/config snapshot differs")
    require(digest_tree(snapshot / "data") == original_data,
            "original moodledata snapshot differs")
    require("config.php" in original_code,
            "Moodle config.php must be present in full code snapshot")
    require(isinstance(dbargs, list) and
            any(str(item) == "-h127.0.0.1" for item in dbargs) and
            all("production" not in str(item).lower() for item in dbargs),
            "only isolated MySQL connection allowed")
    target = root / "independent-restore"
    require(not target.exists() and not target.is_symlink(),
            "independent restore location must not exist")

    created_database = False
    try:
        target.mkdir(mode=0o700)
        shutil.copytree(snapshot / "code", target / "code")
        shutil.copytree(snapshot / "data", target / "moodledata")
        require(digest_tree(target / "code") == original_code,
                "independently restored code/config mismatch")
        require(digest_tree(target / "moodledata") == original_data,
                "independently restored moodledata mismatch")
        cmd(["mysql", *dbargs, "-e",
             "CREATE DATABASE " + DB +
             " CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"],
            stdout=subprocess.DEVNULL)
        created_database = True
        with source_sql.open("rb") as backup:
            cmd(["mysql", *dbargs, DB], stdin=backup, stdout=subprocess.DEVNULL)
        independent_dump = target / "independent-restored.sql"
        with independent_dump.open("wb") as out:
            cmd(["mysqldump", *dbargs, "--single-transaction",
                 "--skip-comments", "--skip-dump-date", DB], stdout=out)
        require(independent_dump.read_bytes() == source_sql.read_bytes(),
                "independently restored entire SQL database differs")
        require(digest_tree(target / "code") == original_code,
                "restoration changed independent code/config")
        require(digest_tree(target / "moodledata") == original_data,
                "restoration changed independent moodledata")
        # The clone config is intentionally NOT booted. It has original
        # references; we verify exact bytes and keep it offline.
        return {
            "status": "PASS",
            "scope": "real synthetic Moodle complete SQL + code/config + moodledata separate restore",
            "independent_database_restored": True,
            "independent_code_and_config_verified": True,
            "independent_moodledata_verified": True,
            "independent_clone_booted": False,
            "production_or_shared_dev_accessed": False,
            "sql_sha256": original_sql_sha256,
            "code_file_count": len(original_code),
            "moodledata_file_count": len(original_data),
        }
    finally:
        if created_database:
            # Only the database generated by this CI rehearsal.
            cmd(["mysql", *dbargs, "-e", "DROP DATABASE " + DB],
                stdout=subprocess.DEVNULL)
        if target.exists():
            shutil.rmtree(target)
